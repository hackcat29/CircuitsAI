/** Thin JSON fetch wrapper shared by every social hook — throws with the server's `error`
 * message (see lib/server/socialErrors.ts's errorResponse) rather than a bare status code. */
export async function socialFetch<T>(input: string, init?: RequestInit): Promise<T> {
  const res = await fetch(input, {
    ...init,
    headers: { "Content-Type": "application/json", ...(init?.headers ?? {}) },
  });
  if (!res.ok) {
    const body = await res.json().catch(() => null);
    throw new Error(body?.error ?? `Request failed (${res.status})`);
  }
  return res.json() as Promise<T>;
}
